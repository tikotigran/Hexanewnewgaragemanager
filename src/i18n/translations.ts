export function localizeCategory(
  cat: { label_fr?: string; label_ru?: string; label_en?: string },
  lang: Language
): string {
  if (lang === 'ru' && cat.label_ru) return cat.label_ru;
  if (lang === 'en' && cat.label_en) return cat.label_en;
  return cat.label_fr || cat.label_en || cat.label_ru || '';
}

export function translateValue(
  t: (key: string) => string,
  prefix: string,
  val: string | null | undefined
): string {
  if (!val) return '—';
  const key = `${prefix}.${val}`;
  const translated = t(key);
  return translated === key ? val : translated;
}
